// RedactConfig builds the API-response (UI-visible) configuration view.
//
// Unlike a naive pass-through, it returns a canonical map containing every
// supported option with its effective value applied (defaults filled in from the
// Default* constants), with secret values masked. This lets the Bifrost UI render
// a complete configuration form even when the user has not set every field.
func RedactConfig(config map[string]any) (map[string]any, error) {
	cfg, err := parseConfig(config)
	if err != nil {
		return nil, err
	}
	cfg.ApplyDefaults()
	return redactedView(cfg), nil
}

// redactedView converts a parsed PluginConfig into the canonical, redacted
// key/value map for API responses. Callers should have applied defaults first.
func redactedView(cfg *PluginConfig) map[string]any {
	if cfg == nil {
		cfg = &PluginConfig{}
	}
	models := cfg.Models
	if models == nil {
		models = []string{}
	}
	mapping := cfg.ModelMapping
	if mapping == nil {
		mapping = map[string]string{}
	}

	return map[string]any{
		"access_token":   redactSecret(cfg.AccessToken),
		"account_id":     cfg.AccountID,
		"token_file":     cfg.TokenFile,
		"auth_issuer":    firstNonEmpty(cfg.AuthIssuer, DefaultAuthIssuer),
		"auth_client_id": firstNonEmpty(cfg.AuthClientID, DefaultAuthClientID),
		"api_base":       firstNonEmpty(cfg.APIBase, DefaultAPIBase),
		"max_retries":    cfg.MaxRetries,
		"models":         models,
		"model_mapping":  mapping,
	}
}

// DescribeConfig returns a human/machine readable description of every
// configuration option this plugin supports. It is an additive export (not part
// of the bifrost loader contract) intended for UIs that want to render a
// configuration form with labels, types, defaults, and descriptions.
func DescribeConfig() map[string]any {
	fields := describeConfigFields()
	out := make(map[string]any, len(fields))
	for _, f := range fields {
		out[f.Key] = map[string]any{
			"kind":        f.Kind,
			"description": f.Description,
			"default":     f.Default,
		}
	}

	// Auth guidance field describing the interactive device flow that the
	// plugin surfaces in logs/status. This makes the plugin description
	// self-documenting about how to authenticate.
	if status := GetAuthStatus(); status != nil {
		out["_auth"] = map[string]any{
			"kind":        "status",
			"description": "Device-flow auth status. When not authenticated the plugin logs the verification URL and one-time code and re-polls until you authorize.",
			"value":       status,
		}
	}
	return out
}

// redactSecret returns "***" for a non-empty secret and "" otherwise, so a UI can
// distinguish "set (hidden)" from "unset".
func redactSecret(v string) string {
	if v == "" {
		return ""
	}
	return "***"
}

// firstNonEmpty returns v when non-empty, otherwise fallback.
func firstNonEmpty(v, fallback string) string {
	if v != "" {
		return v
	}
	return fallback
}