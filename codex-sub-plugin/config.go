// PluginConfig is the configuration for the Codex Subscription plugin.
// It is deserialized from the "config" field in Bifrost's plugin configuration.
type PluginConfig struct {
	// AccessToken is the ChatGPT/Codex session access token (Bearer token from
	// chatgpt.com). If set, this takes precedence over TokenFile.
	// Extract from the Codex CLI's auth storage or a browser session.
	AccessToken string `json:"access_token"`

	// AccountID is the `chatgpt_account_id` claim from the OAuth ID token.
	// It is sent as the `ChatGPT-Account-Id` header to the Codex backend.
	AccountID string `json:"account_id,omitempty"`

	// TokenFile is the path to a JSON file containing OAuth tokens
	// (generated by the codex-sub-login CLI tool).
	// If AccessToken is empty, the plugin reads tokens from this file.
	// Default: ~/.bifrost/codex-auth.json
	TokenFile string `json:"token_file,omitempty"`

	// AuthIssuer is the OAuth issuer URL for token refresh.
	// Only needed if TokenFile is used and token refresh is desired.
	// Default: "https://auth.openai.com"
	AuthIssuer string `json:"auth_issuer,omitempty"`

	// AuthClientID is the OAuth client ID for token refresh.
	// Only needed if TokenFile is used and token refresh is desired.
	// Default: "app_EMoamEEZ73f0CkXaXp7hrann"
	AuthClientID string `json:"auth_client_id,omitempty"`

	// Models is the list of OpenAI model names to intercept.
	// Requests with any of these models (when provider is "openai") will be
	// rerouted through the Codex backend Responses API.
	Models []string `json:"models"`

	// ModelMapping optionally overrides the default OpenAI→Codex model slug mapping.
	ModelMapping map[string]string `json:"model_mapping,omitempty"`

	// APIBase optionally overrides the ChatGPT backend API base URL.
	// Default: "https://chatgpt.com/backend-api"
	APIBase string `json:"api_base,omitempty"`

	// MaxRetries optionally sets the number of retries for failed HTTP calls.
	// Default: 0 (no retries).
	MaxRetries int `json:"max_retries,omitempty"`
}

